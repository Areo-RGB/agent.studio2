import JSZip from 'jszip';
import { AIToolId, McpServer, Skill, PromptPreset, AI_TOOLS } from '../types';
import { generateToolMcpConfig } from './mcpSerializers';
import { generatePromptExport } from './promptGenerators';

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function downloadTextFile(content: string, filename: string, mimeType = 'text/plain'): void {
  const blob = new Blob([content], { type: mimeType });
  downloadBlob(blob, filename);
}

/**
 * Creates a ZIP archive for a single Skill preserving its folder structure.
 */
export async function createSingleSkillZip(skill: Skill): Promise<Blob> {
  const zip = new JSZip();
  const folderName = skill.id;
  const folder = zip.folder(folderName) || zip;

  // Add SKILL.md
  folder.file('SKILL.md', skill.skillMdContent);

  // Add supporting files
  for (const file of skill.files) {
    if (file.path !== 'SKILL.md') {
      folder.file(file.path, file.content);
    }
  }

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Creates a ZIP for a single Skill formatted for a specific target AI tool.
 */
export async function createSkillZipForTool(skill: Skill, toolId: AIToolId): Promise<Blob> {
  const zip = new JSZip();
  const toolMeta = AI_TOOLS[toolId];

  // Tool-specific folder path, e.g. "skills/code-review/..."
  const skillFolder = zip.folder(`skills/${skill.id}`) || zip;
  skillFolder.file('SKILL.md', skill.skillMdContent);

  for (const file of skill.files) {
    if (file.path !== 'SKILL.md') {
      skillFolder.file(file.path, file.content);
    }
  }

  // Add instruction README
  zip.file(
    'INSTALL_INSTRUCTIONS.md',
    `# Installation Instructions for ${toolMeta.name}

To use this skill with ${toolMeta.name}:
1. Copy the "skills/${skill.id}" folder into your ${toolMeta.name} skills directory:
   Target path: ${toolMeta.skillsPath}/${skill.id}

2. Ensure ${skill.id}/SKILL.md exists in that location.

Generated by Agent Config Studio.
`
  );

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Creates a ZIP of all enabled skills organized for chosen tools.
 */
export async function createAllEnabledSkillsZip(
  skills: Skill[],
  selectedTools: AIToolId[]
): Promise<Blob> {
  const zip = new JSZip();

  let totalSkillsAdded = 0;

  for (const toolId of selectedTools) {
    const toolMeta = AI_TOOLS[toolId];
    const enabledSkills = skills.filter((s) => s.enabledTools[toolId]);
    if (enabledSkills.length === 0) continue;

    const toolFolder = zip.folder(toolId) || zip;

    for (const skill of enabledSkills) {
      const skillFolder = toolFolder.folder(`skills/${skill.id}`) || toolFolder;
      skillFolder.file('SKILL.md', skill.skillMdContent);
      for (const file of skill.files) {
        if (file.path !== 'SKILL.md') {
          skillFolder.file(file.path, file.content);
        }
      }
      totalSkillsAdded++;
    }

    toolFolder.file(
      'README.md',
      `# ${toolMeta.name} Skills Directory\n\nPlace all folders inside "skills/" into ${toolMeta.skillsPath}/`
    );
  }

  zip.file(
    'README.md',
    `# Agent Config Studio - Exported Skills Library

This ZIP archive contains your selected skills packaged for:
${selectedTools.map((t) => `- ${AI_TOOLS[t].name}: Destination ${AI_TOOLS[t].skillsPath}`).join('\n')}

Note: Agent Config Studio runs client-side in your browser. Copy the respective skill folders into your local AI tool directories.
`
  );

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Creates a complete tool bundle ZIP containing:
 * - MCP config file
 * - Prompt file
 * - Enabled skills
 * - README instructions
 */
export async function createToolBundleZip(
  toolId: AIToolId,
  mcpServers: McpServer[],
  skills: Skill[],
  activePrompt?: PromptPreset,
  redactSecrets = true
): Promise<Blob> {
  const zip = new JSZip();
  const toolMeta = AI_TOOLS[toolId];

  // 1. MCP Configuration
  const mcpExport = generateToolMcpConfig(toolId, mcpServers, { redactSecrets });
  const mcpFilename =
    toolId === 'claude'
      ? '.claude.json'
      : toolId === 'codex'
      ? 'config.toml'
      : toolId === 'pi'
      ? 'mcp.json'
      : 'opencode.json';
  zip.file(mcpFilename, mcpExport.content);

  // 2. Prompt Preset
  const promptExport = generatePromptExport(toolId, activePrompt);
  if (promptExport.hasActivePrompt) {
    zip.file(promptExport.fileName, promptExport.content);
  }

  // 3. Skills
  const enabledSkills = skills.filter((s) => s.enabledTools[toolId]);
  const skillsFolder = zip.folder('skills');
  if (skillsFolder) {
    for (const skill of enabledSkills) {
      const folder = skillsFolder.folder(skill.id);
      if (folder) {
        folder.file('SKILL.md', skill.skillMdContent);
        for (const file of skill.files) {
          if (file.path !== 'SKILL.md') {
            folder.file(file.path, file.content);
          }
        }
      }
    }
  }

  // 4. README
  zip.file(
    'README.md',
    `# ${toolMeta.name} Configuration Bundle

Generated by Agent Config Studio on ${new Date().toISOString()}.

## Included Files & Target Locations:

1. **MCP Servers (${mcpExport.serverCount} enabled)**:
   - Source: \`${mcpFilename}\`
   - Target location on your system: \`${toolMeta.mcpPath}\`
   ${redactSecrets ? '- *Note*: Sensitive credentials were redacted with ***REDACTED_SECRET*** placeholders. Replace with your actual credentials.' : ''}

2. **System Prompt Preset**:
   ${promptExport.hasActivePrompt ? `- Source: \`${promptExport.fileName}\` (Preset: "${promptExport.presetName}")\n   - Target location: \`${toolMeta.promptPath}\`` : '- No prompt preset was active for this tool.'}

3. **Skills (${enabledSkills.length} enabled)**:
   - Source: \`skills/\` directory
   - Target location: \`${toolMeta.skillsPath}/\`
   - Enabled skills: ${enabledSkills.map((s) => s.name).join(', ') || 'None'}

### Important Disclaimer
This archive was generated client-side by Agent Config Studio. It does NOT automatically modify or sync files to your computer. Please manually copy the desired configuration files to the paths listed above. Always backup existing configurations before replacing them!
`
  );

  return zip.generateAsync({ type: 'blob' });
}

/**
 * Creates a complete workspace ZIP with folders for each selected tool.
 */
export async function createWorkspaceBundleZip(
  selectedTools: AIToolId[],
  mcpServers: McpServer[],
  skills: Skill[],
  prompts: PromptPreset[],
  redactSecrets = true
): Promise<Blob> {
  const zip = new JSZip();

  for (const toolId of selectedTools) {
    const toolMeta = AI_TOOLS[toolId];
    const toolFolder = zip.folder(toolId) || zip;

    // MCP
    const mcpExport = generateToolMcpConfig(toolId, mcpServers, { redactSecrets });
    const mcpFilename =
      toolId === 'claude'
        ? '.claude.json'
        : toolId === 'codex'
        ? 'config.toml'
        : toolId === 'pi'
        ? 'mcp.json'
        : 'opencode.json';
    toolFolder.file(mcpFilename, mcpExport.content);

    // Prompt
    const activePrompt = prompts.find((p) => p.toolId === toolId && p.isActive);
    const promptExport = generatePromptExport(toolId, activePrompt);
    if (promptExport.hasActivePrompt) {
      toolFolder.file(promptExport.fileName, promptExport.content);
    }

    // Skills
    const enabledSkills = skills.filter((s) => s.enabledTools[toolId]);
    const skillsFolder = toolFolder.folder('skills');
    if (skillsFolder) {
      for (const skill of enabledSkills) {
        const folder = skillsFolder.folder(skill.id);
        if (folder) {
          folder.file('SKILL.md', skill.skillMdContent);
          for (const file of skill.files) {
            if (file.path !== 'SKILL.md') {
              folder.file(file.path, file.content);
            }
          }
        }
      }
    }

    toolFolder.file(
      'INSTALL.md',
      `# ${toolMeta.name} Installation Instructions\n\nCopy ${mcpFilename} to ${toolMeta.mcpPath}\nCopy prompt to ${toolMeta.promptPath}\nCopy skills/ into ${toolMeta.skillsPath}/`
    );
  }

  zip.file(
    'README.md',
    `# Master Workspace Configuration Bundle
Generated by Agent Config Studio.

Included tools:
${selectedTools.map((t) => `- ${AI_TOOLS[t].name} (folder: ${t}/)`).join('\n')}

Review the INSTALL.md file within each subfolder for exact system directory locations.
Remember: Backup any existing system configuration files prior to applying these exports.
`
  );

  return zip.generateAsync({ type: 'blob' });
}

export interface ImportedSkillData {
  id: string;
  name: string;
  description: string;
  skillMdContent: string;
  files: { path: string; content: string }[];
  tags: string[];
}

/**
 * Parses an uploaded ZIP file to extract Skills.
 * Detects SKILL.md files and associated directory assets.
 */
export async function parseSkillsFromZip(zipFile: File): Promise<ImportedSkillData[]> {
  const zip = await JSZip.loadAsync(zipFile);
  const results: ImportedSkillData[] = [];

  // Group files by skill directory
  const skillRoots = new Map<string, string[]>(); // rootPrefix -> list of relative paths

  zip.forEach((relativePath, entry) => {
    if (entry.dir) return;

    // Check if filename is SKILL.md
    const segments = relativePath.split('/');
    const fileName = segments[segments.length - 1];

    if (fileName.toLowerCase() === 'skill.md') {
      const rootPrefix = segments.slice(0, -1).join('/');
      if (!skillRoots.has(rootPrefix)) {
        skillRoots.set(rootPrefix, []);
      }
    }
  });

  // Now assign files to each skill root
  for (const [rootPrefix] of skillRoots.entries()) {
    const skillFiles: { path: string; content: string }[] = [];
    let skillMdContent = '';

    const prefixSlash = rootPrefix ? `${rootPrefix}/` : '';

    const matchingPaths: string[] = [];
    zip.forEach((relPath) => {
      if (rootPrefix === '' || relPath.startsWith(prefixSlash)) {
        // Check it belongs directly to this root (doesn't hit another child SKILL.md)
        matchingPaths.push(relPath);
      }
    });

    for (const relPath of matchingPaths) {
      const entry = zip.file(relPath);
      if (!entry) continue;

      const subPath = rootPrefix ? relPath.substring(prefixSlash.length) : relPath;
      const text = await entry.async('string');

      if (subPath.toLowerCase() === 'skill.md') {
        skillMdContent = text;
      }
      skillFiles.push({ path: subPath, content: text });
    }

    if (skillMdContent) {
      // Parse frontmatter
      const { name, description, tags } = parseSkillFrontmatter(skillMdContent, rootPrefix);
      const fallbackId = rootPrefix.split('/').pop() || 'imported-skill';
      results.push({
        id: slugify(name || fallbackId),
        name: name || fallbackId,
        description: description || 'Imported Skill',
        skillMdContent,
        files: skillFiles,
        tags,
      });
    }
  }

  return results;
}

/**
 * Simple YAML frontmatter parser for SKILL.md
 */
export function parseSkillFrontmatter(
  content: string,
  fallbackName?: string
): { name: string; description: string; tags: string[] } {
  let name = fallbackName || 'new-skill';
  let description = '';
  const tags: string[] = [];

  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (match) {
    const yaml = match[1];
    const nameMatch = yaml.match(/^name:\s*["']?([^"'\r\n]+)["']?/m);
    if (nameMatch) name = nameMatch[1].trim();

    const descMatch = yaml.match(/^description:\s*["']?([^"'\r\n]+)["']?/m);
    if (descMatch) description = descMatch[1].trim();

    const tagsMatch = yaml.match(/^tags:\s*\[([^\]]*)\]/m);
    if (tagsMatch) {
      tagsMatch[1]
        .split(',')
        .map((t) => t.trim().replace(/^["']|["']$/g, ''))
        .filter(Boolean)
        .forEach((t) => tags.push(t));
    }
  }

  return { name, description, tags };
}

function slugify(text: string): string {
  return text
    .toLowerCase()
    .trim()
    .replace(/[^\w\s-]/g, '')
    .replace(/[\s_-]+/g, '-')
    .replace(/^-+|-+$/g, '') || 'skill';
}
